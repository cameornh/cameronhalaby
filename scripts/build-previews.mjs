// Run with `node scripts/build-previews.mjs` on macOS after adding gallery images.
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = path.join(root, 'assets');
const output = path.join(assets, 'previews');
mkdirSync(output, { recursive: true });
const previews = {};
for (const name of readdirSync(assets).sort()) {
    if (!/^(ar|p|pr|strip)\d+[a-z]*\.(jpe?g|png|webp)$/i.test(name)) continue;
    const target = path.join(output, name + '.jpg');
    execFileSync('sips', ['-s', 'format', 'jpeg', '-s', 'formatOptions', '82', '-Z', name.startsWith('strip') ? '1920' : '960', path.join(assets, name), '--out', target], { stdio: 'pipe' });
    const info = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', target], { encoding: 'utf8' });
    previews[name] = { src: './assets/previews/' + name + '.jpg', width: Number(info.match(/pixelWidth: (\d+)/)[1]), height: Number(info.match(/pixelHeight: (\d+)/)[1]) };
}
writeFileSync(path.join(root, 'asset-previews.js'), '// Generated by scripts/build-previews.mjs. Originals are retained for lightboxes.\nwindow.CameronPreviews = ' + JSON.stringify(previews, null, 2) + ';\n');
console.log('Built ' + Object.keys(previews).length + ' image previews.');
